# Builds js/data/geo.js from sourced geography:
#  - SF land + parks: DataSF "Analysis Neighborhoods" (data.sfgov.org j2bu-swwd)
#  - Alcatraz + surrounding counties: US Census cartographic boundaries 2023 (1:500k)
import json, shapefile
from shapely.geometry import shape, box, Polygon, MultiPolygon
from shapely.ops import unary_union, transform
LON0, LAT0, MX, MZ = -122.44, 37.77, 88000.0, 111000.0
proj = lambda x, y, z=None: ((x - LON0) * MX, -(y - LAT0) * MZ)
g = json.load(open('/tmp/j2bu-swwd.geojson'))
nb = {f['properties']['nhood']: shape(f['geometry']).buffer(0) for f in g['features']}
sf = unary_union(list(nb.values()))
r = shapefile.Reader('/tmp/cb/cb_2023_us_county_500k')
flds = [f[0] for f in r.fields[1:]]
far, alcatraz = [], None
bb = box(LON0 - 0.43, LAT0 - 0.34, LON0 + 0.43, LAT0 + 0.34)
for sr in r.iterShapeRecords():
    rec = dict(zip(flds, sr.record))
    if rec['STATEFP'] != '06': continue
    s = shape(sr.shape.__geo_interface__).buffer(0)
    if rec['NAME'] == 'San Francisco':
        for p in s.geoms:
            b = p.bounds
            if abs(b[0] + 122.4254) < 0.002 and abs(b[1] - 37.8252) < 0.002: alcatraz = p
            elif b[1] > 37.85 or b[0] > -122.34: far.append(p)   # slivers of Angel Island / Alameda
    elif rec['NAME'] in ('Marin', 'San Mateo', 'Alameda', 'Contra Costa', 'Sonoma', 'Solano', 'Napa', 'Santa Clara'):
        c = s.intersection(bb)
        if not c.is_empty: far.append(c)
def parts(geom):
    return [geom] if isinstance(geom, Polygon) else [p for p in geom.geoms if isinstance(p, Polygon)]
def rings(geom, tol, min_area):
    out = []
    for p in parts(transform(proj, geom)):
        p = Polygon(p.exterior).simplify(tol, preserve_topology=True)   # drop holes (seams between outlines)
        if p.area < min_area: continue
        c = list(p.exterior.coords)[:-1]
        out.append([round(v, 1) for xy in c for v in xy])
    return out
# close hairline seams between neighbourhood outlines, then restore the outline
sfm = transform(proj, sf).buffer(1.5).buffer(-1.5)
land = []
for p in parts(sfm):
    p = Polygon(p.exterior).simplify(2.0)
    if p.area < 1500: continue
    land.append([round(v, 1) for xy in list(p.exterior.coords)[:-1] for v in xy])
alc = transform(proj, alcatraz).buffer(40, resolution=4).buffer(-40, resolution=4).buffer(12, resolution=4)  # soften the 7-point outline
land.append([round(v, 1) for xy in list(alc.exterior.coords)[:-1] for v in xy])
farr = rings(unary_union(far), 25.0, 20000)
ggp = rings(nb['Golden Gate Park'], 3.0, 1000)
pre = rings(nb['Presidio'], 3.0, 1000)
js = "// Generated by tools/build_geo.py. Coordinates are metres: x east, z south of (LON0, LAT0).\n"
js += "// Sources: DataSF Analysis Neighborhoods (SF land, parks); US Census cartographic boundaries 2023 (Alcatraz, other counties).\n"
js += f"export const LON0 = {LON0}, LAT0 = {LAT0}, MX = {MX}, MZ = {MZ};\n"
for name, v in (('LAND', land), ('FAR_LAND', farr), ('PARK_GGP', ggp), ('PARK_PRESIDIO', pre)):
    js += f"export const {name} = {json.dumps(v, separators=(',', ':'))};\n"
open('js/data/geo.js', 'w').write(js)
print('land rings', len(land), [len(x)//2 for x in land]); print('far', len(farr), sum(len(x) for x in farr)//2)
print('ggp', [len(x)//2 for x in ggp], 'presidio', [len(x)//2 for x in pre], 'bytes', len(js))
